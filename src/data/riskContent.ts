export interface FactorItem {
  id: string;
  group: 'external' | 'internal';
  category: string;
  title: string;
  description: string;
  example: string;
}

export interface RiskZone {
  id: string;
  index: number;
  label: string;
  levelCode: string;
  severity: 'safe' | 'low' | 'moderate' | 'high' | 'critical';
  summary: string;
  financialImpact: string;
  managementAction: string;
}

export interface RiskStrategy {
  id: string;
  name: string;
  category: 'Уклонение и удержание' | 'Трансфер и страхование' | 'Структурное снижение';
  mechanism: string;
  innovationContext: string;
}

export interface PortfolioInput {
  id: number;
  name: string;
  cost: number; // x_i, тыс. руб.
  projects: number; // N
  fails: number; // v_i
}

